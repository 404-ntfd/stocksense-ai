import { test, type Page } from '@playwright/test';
import { onboardWithDemo, ask } from '../e2e/helpers';

const shot = (page: Page, name: string, fullPage = false) => page.screenshot({ path: `docs/img/${name}.jpg`, type: 'jpeg', quality: 78, fullPage });

test('product screenshots', async ({ page }) => {
  test.setTimeout(180_000);
  await page.addInitScript(() => { (window as unknown as { __SS_MOCK_SPEECH__: boolean }).__SS_MOCK_SPEECH__ = true; });
  await page.goto('/');
  await page.getByTestId('onboarding').waitFor();
  await shot(page, '01-onboarding');
  await onboardWithDemo(page);
  await page.getByTestId('toast').waitFor({ state: 'detached', timeout: 10_000 }).catch(() => {});
  await page.waitForTimeout(600);
  await shot(page, '02-dashboard');
  await page.evaluate(() => document.querySelector('main')?.scrollTo(0, 820));
  await page.waitForTimeout(400);
  await shot(page, '03-dashboard-charts');
  await page.goto('/#/inventory');
  await page.getByTestId('product-row').first().waitFor();
  await shot(page, '04-inventory');
  await page.goto('/#/inventory/61');
  await page.getByTestId('product-chart').locator('canvas').waitFor();
  await page.waitForTimeout(500);
  await shot(page, '05-product-detail');
  await page.goto('/#/ask');
  await shot(page, '06-ask-empty');
  await ask(page, 'top 5 products last month');
  await page.waitForTimeout(600);
  await shot(page, '07-ask-answer');
  await page.getByTestId('mic').click();
  await page.evaluate(() => { const m = (window as unknown as { __SS_MOCK_SPEECH__: { fire: (e: string, p: unknown) => void } }).__SS_MOCK_SPEECH__; m.fire('partial', 'when will sugar'); m.fire('level', 0.6); });
  await page.waitForTimeout(300);
  await shot(page, '08-voice-listening');
  await page.getByTestId('mic').click();
  await page.goto('/#/ask');
  await ask(page, 'received 24 Tata Salt 1kg at 21');
  await page.waitForTimeout(300);
  await shot(page, '09-confirm-card');
  await page.goto('/#/insights');
  await page.getByTestId('reorder-list').locator('li').first().waitFor({ timeout: 20_000 });
  await page.waitForTimeout(800);
  await shot(page, '10-insights');
  await page.goto('/#/data');
  await page.getByTestId('table-list').waitFor();
  await shot(page, '11-data');
  await page.goto('/#/data/import');
  await page.getByTestId('import-file').setInputFiles('samples/demo_sales.xlsx');
  await page.getByTestId('mapping').waitFor({ timeout: 20_000 });
  await page.waitForTimeout(300);
  await shot(page, '12-import-mapping');
  await page.getByTestId('import-next').click();
  await page.getByTestId('import-run').click();
  await page.getByTestId('import-report').waitFor({ timeout: 30_000 });
  await shot(page, '13-import-report');
  await page.goto('/#/more');
  await page.getByTestId('key-field').waitFor();
  await shot(page, '14-settings');
  await page.getByTestId('theme').getByRole('tab', { name: 'Dark' }).click();
  await page.goto('/');
  await page.getByTestId('kpi-revenue-value').waitFor();
  await page.waitForTimeout(600);
  await shot(page, '15-dashboard-dark');
});

test('desktop (Windows) screenshot', async ({ browser }) => {
  const ctx = await browser.newContext({ viewport: { width: 1366, height: 820 }, deviceScaleFactor: 1, serviceWorkers: 'block', locale: 'en-IN', timezoneId: 'Asia/Kolkata' });
  const page = await ctx.newPage();
  await onboardWithDemo(page);
  await page.getByTestId('toast').waitFor({ state: 'detached', timeout: 10_000 }).catch(() => {});
  await page.waitForTimeout(800);
  await page.screenshot({ path: 'docs/img/16-desktop.jpg', type: 'jpeg', quality: 78 });
  await ctx.close();
});
